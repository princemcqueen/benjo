def inject_into_sim(sim, hv=None):
    """Registers the Haven terrain in the simulator as an analytic heightfield
    (exactly the in-game column function) and marks it prebuilt so the Luau
    builder skips the (slow in the simulator) voxel writing."""
    import rbx_terrain
    hv = hv or HV.Haven().build()
    ref = Reference(hv)

    def fn(x, z):
        h, m, w = ref.sample(np.array([x]), np.array([z]))
        return float(h[0]), HV.MATS[int(m[0])], float(w[0])

    st = rbx_terrain.get_store(sim)
    st.add_heightfield(fn, -HV.EXTENT, -HV.EXTENT, HV.EXTENT, HV.EXTENT, 0, float(hv.H.max()) + 8)
    sim.terrain.attrs["Prebuilt"] = "Haven"
    sim.haven = hv
    return ref
